/** CHANGELOG -> "What's new" data (pure; used by scripts/whats-new.ts, the vite plugin and tests). docs/pwa.md "Update card". */
export interface WhatsNewEntry { version: string; date: string; highlights: string[] }
export const WHATS_NEW_VERSIONS = 3;
export const MAX_HIGHLIGHTS = 6;
const MAX_LEN = 150;

/** Plain-text a markdown bullet: links, bold, code, trailing doc refs. */
export function plainText(s: string): string {
  return s.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/\*\*([^*]+)\*\*/g, '$1').replace(/`([^`]+)`/g, '$1').replace(/\*([^*]+)\*/g, '$1').replace(/\s+/g, ' ').trim();
}
function clip(s: string): string {
  if (s.length <= MAX_LEN) return s;
  const cut = s.slice(0, MAX_LEN - 1), sp = cut.lastIndexOf(' ');
  return `${cut.slice(0, sp > 60 ? sp : cut.length).replace(/[,;:.\s]+$/, '')}\u2026`;
}
/** Newest released sections of the changelog (`## [x.y.z] - date`, "Unreleased" skipped). Uses the `### Highlights` bullets, else the first 4 top-level bullets. */
export function parseChangelog(md: string, versions = WHATS_NEW_VERSIONS): WhatsNewEntry[] {
  const lines = md.split(/\r?\n/);
  const out: WhatsNewEntry[] = [];
  let cur: { version: string; date: string; hl: string[]; first: string[]; inHl: boolean } | null = null;
  const flush = (): void => {
    if (!cur) return;
    const src = cur.hl.length ? cur.hl : cur.first.slice(0, 4);
    out.push({ version: cur.version, date: cur.date, highlights: src.slice(0, MAX_HIGHLIGHTS).map((b) => clip(plainText(b))) });
    cur = null;
  };
  for (const ln of lines) {
    const h2 = /^## \[(\d+\.\d+\.\d+)\]\s*-\s*(\d{4}-\d{2}-\d{2})/.exec(ln);
    if (h2) { flush(); if (out.length >= versions) break; cur = { version: h2[1]!, date: h2[2]!, hl: [], first: [], inHl: false }; continue; }
    if (/^## /.test(ln)) { flush(); if (out.length >= versions) break; continue; }
    if (!cur) continue;
    if (/^###\s/.test(ln)) { cur.inHl = /^###\s+Highlights\s*$/i.test(ln); continue; }
    const b = /^- (.+)$/.exec(ln);
    if (!b) continue;
    if (cur.inHl) cur.hl.push(b[1]!); else cur.first.push(b[1]!);
  }
  flush();
  return out.slice(0, versions);
}
export const renderGenerated = (e: readonly WhatsNewEntry[]): string =>
  `// GENERATED by scripts/whats-new.ts from CHANGELOG.md (### Highlights). Do not edit: run \`npm run whats-new\`.\n` +
  `import type { WhatsNewEntry } from './whatsNew';\n\nexport const WHATS_NEW: readonly WhatsNewEntry[] = ${JSON.stringify(e, null, 2)};\n`;
export const renderJson = (e: readonly WhatsNewEntry[]): string => `${JSON.stringify({ entries: e })}\n`;
