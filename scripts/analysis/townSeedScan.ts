/**
 * Scans seeds per town archetype / size and prints the vetted ones (few failures, valid, nice score).
 *   npx vite-node scripts/analysis/townSeedScan.ts -- [town] [size] [from] [count] [minScore]
 * Paste the output into src/config/townSeeds.ts. Not part of the default tests.
 */
import { createSim } from '../../src/game/createSim';
import { TOWNS, buildTown, townIssues, townSimOptions, townOf } from '../../src/game/demoTowns';
import type { MapSize } from '../../src/core/GameState';

const args = process.argv.slice(2).filter((a) => a !== '--');
const only = args[0] && args[0] !== 'all' ? args[0] : null;
const onlySize = args[1] && args[1] !== 'all' ? Number(args[1]) : null;
const from = Number(args[2] ?? 1), count = Number(args[3] ?? 40), minScore = Number(args[4] ?? 0.5);

const result: Record<string, Record<number, number[]>> = {};
for (const t of TOWNS) {
  if (only && t.id !== only) continue;
  for (const size of t.sizes) {
    if (onlySize && size !== onlySize) continue;
    const good: Array<{ seed: number; score: number; fails: number }> = [];
    for (let seed = from; seed < from + count; seed++) {
      const sim = createSim({ ...townSimOptions(t.id, size as MapSize), seed, now: () => 0 });
      const r = buildTown(sim, t.id, seed);
      const issues = townIssues(sim);
      const ok = r.failures.length <= Math.min(1, townOf(t.id)!.maxFailures) && issues.length === 0 && r.score >= minScore;
      console.log(`${t.id} ${size} seed ${seed}: score ${r.score} fail ${r.failures.length} issues ${issues.length} lifts ${r.lifts.length} ${r.buildMs.toFixed(0)}ms${ok ? ' OK' : ''}${r.failures.length ? ' ' + r.failures.slice(0, 3).join(' | ') : ''}`);
      if (ok) good.push({ seed, score: r.score, fails: r.failures.length });
    }
    good.sort((a, b) => a.fails - b.fails || b.score - a.score);
    (result[t.id] ??= {})[size] = good.slice(0, 8).map((g) => g.seed);
  }
}
console.log('\n' + JSON.stringify(result, null, 1));
if (process.env.WRITE) {
  const body = Object.entries(result).map(([id, bySize]) => `  ${id}: { ${Object.entries(bySize).map(([sz, seeds]) => `${sz}: [${seeds.join(', ')}]`).join(', ')} },`).join('\n');
  const file = `// Generated by scripts/analysis/townSeedScan.ts (WRITE=1). Vetted seeds per town archetype and map size: build with <= 1 failure, valid, nice score.\n// Terrain-visual vetting (day/closeup shots) is documented in docs/demo-towns.md.\nimport type { TownId } from '../game/demoTowns';\n\nexport const TOWN_SEEDS: Record<TownId, Partial<Record<64 | 128 | 256, readonly number[]>>> = {\n${body}\n};\n`;
  (await import('node:fs')).writeFileSync('src/config/townSeeds.ts', file);
  console.log('wrote src/config/townSeeds.ts');
}
